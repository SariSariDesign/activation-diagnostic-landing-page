#!/usr/bin/env node
/**
 * Stamp GA4 + Microsoft Clarity tracking into the static report HTML files.
 *
 * The diagnostic reports under public/reports/<slug>/index.html are plain
 * static HTML — they do NOT go through the Next.js layout, so they never pick
 * up the analytics scripts added in src/app/layout.tsx. This script injects the
 * same two snippets directly into each report's <head>.
 *
 * Behaviour:
 *   - Reads NEXT_PUBLIC_GA_ID / NEXT_PUBLIC_CLARITY_ID from the environment.
 *   - If neither is set, it no-ops (so local/dev builds don't bake in tracking).
 *   - The injected block is wrapped in marker comments and is IDEMPOTENT:
 *     re-running replaces the existing block instead of duplicating it.
 *
 * Usage:
 *   npm run inject-analytics      # manual, after adding a new report
 *   (also runs automatically via the `prebuild` script on every build)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { readdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPORTS_DIR = join(__dirname, "..", "public", "reports");

const GA_ID = process.env.NEXT_PUBLIC_GA_ID ?? "";
const CLARITY_ID = process.env.NEXT_PUBLIC_CLARITY_ID ?? "";

const START = "<!-- analytics:start (auto-generated by scripts/inject-analytics.mjs — do not edit) -->";
const END = "<!-- analytics:end -->";

function buildSnippet() {
  const parts = [START];

  if (GA_ID) {
    parts.push(
      `<script async src="https://www.googletagmanager.com/gtag/js?id=${GA_ID}"></script>`,
      `<script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag('js',new Date());gtag('config','${GA_ID}');</script>`
    );
  }

  if (CLARITY_ID) {
    parts.push(
      `<script>(function(c,l,a,r,i,t,y){c[a]=c[a]||function(){(c[a].q=c[a].q||[]).push(arguments)};t=l.createElement(r);t.async=1;t.src="https://www.clarity.ms/tag/"+i;y=l.getElementsByTagName(r)[0];y.parentNode.insertBefore(t,y);})(window,document,"clarity","script","${CLARITY_ID}");</script>`
    );
  }

  parts.push(END);
  return parts.join("\n");
}

/** Recursively find every index.html under public/reports/. */
async function findReportHtml(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return []; // no reports dir yet
  }
  const out = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...(await findReportHtml(full)));
    } else if (entry.isFile() && entry.name.endsWith(".html")) {
      out.push(full);
    }
  }
  return out;
}

/** Remove any previously-injected block so re-runs don't duplicate. */
function stripExisting(html) {
  const startIdx = html.indexOf(START);
  if (startIdx === -1) return html;
  const endIdx = html.indexOf(END, startIdx);
  if (endIdx === -1) return html; // malformed; leave as-is
  const after = endIdx + END.length;
  // also swallow a single trailing newline we may have added
  const tail = html[after] === "\n" ? after + 1 : after;
  return html.slice(0, startIdx) + html.slice(tail);
}

async function main() {
  if (!GA_ID && !CLARITY_ID) {
    console.log(
      "[inject-analytics] No NEXT_PUBLIC_GA_ID / NEXT_PUBLIC_CLARITY_ID set — skipping report injection."
    );
    return;
  }

  const files = await findReportHtml(REPORTS_DIR);
  if (files.length === 0) {
    console.log("[inject-analytics] No report HTML files found under public/reports/.");
    return;
  }

  const snippet = buildSnippet();
  let changed = 0;

  for (const file of files) {
    const original = readFileSync(file, "utf8");
    const cleaned = stripExisting(original);

    let next;
    if (cleaned.includes("</head>")) {
      next = cleaned.replace("</head>", `${snippet}\n</head>`);
    } else {
      // No <head> (unusual) — prepend so the tags still load.
      next = `${snippet}\n${cleaned}`;
    }

    if (next !== original) {
      writeFileSync(file, next, "utf8");
      changed++;
    }
  }

  console.log(
    `[inject-analytics] Stamped ${changed}/${files.length} report file(s) ` +
      `(GA4: ${GA_ID ? "on" : "off"}, Clarity: ${CLARITY_ID ? "on" : "off"}).`
  );
}

main().catch((err) => {
  console.error("[inject-analytics] Failed:", err);
  process.exit(1);
});
